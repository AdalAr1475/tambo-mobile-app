const byId = new Map(products.map((p) => [p.id, p]));

export const getProduct = (id: string) => byId.get(id);

export const productsByCategory = (categoryId: CategoryId) =>
  products.filter((p) => p.categoryId === categoryId);

export const discountPercent = (p: Pick<Product, 'price' | 'regularPrice'>) =>
  p.regularPrice && p.regularPrice > p.price ? Math.round((1 - p.price / p.regularPrice) * 100) : 0;

export const dealsOfTheDay = () =>
  products
    .filter((p) => discountPercent(p) > 0)
    .sort((a, b) => discountPercent(b) - discountPercent(a))
    .slice(0, 6);

export const combos = () => products.filter((p) => p.promoTags?.includes('combos'));

export const searchProducts = (query: string, pool: Product[] = products) => {
  const q = normalize(query.trim());
  if (!q) return pool;
  return pool.filter((p) => normalize(`${p.name} ${p.brand} ${p.subcategory} ${p.subtitle}`).includes(q));
};

export const normalize = (s: string) => s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '');
